"""Versioned content adapters: render a ManuscriptDocument into a template family's conventions without
modifying any protected template file. The adapter writes only main.tex, content.tex and refs.bib."""

from __future__ import annotations

from rp_contracts.latexdoc import (
    Block,
    ManuscriptDocument,
    RenderOptions,
    Section,
    escape,
    inline,
    safe_filename,
    safe_label,
    sanitize_math,
)

ADAPTER_VERSION = "rp-latex-adapter/1"
ANON_NAME = "Anonymous Author(s)"
ANON_AFFIL = "Anonymous Institution"


class AdapterError(ValueError):
    pass


def _block(b: Block) -> str:
    if b.type == "paragraph":
        return inline(b.text or "") + "\n"
    if b.type == "subsection":
        return "\\subsection{" + escape(b.text or "") + "}\n"
    if b.type == "subsubsection":
        return "\\subsubsection{" + escape(b.text or "") + "}\n"
    if b.type in ("bullet_list", "numbered_list"):
        env = "itemize" if b.type == "bullet_list" else "enumerate"
        return f"\\begin{{{env}}}\n" + "".join(f"  \\item {inline(i)}\n" for i in b.items) + f"\\end{{{env}}}\n"
    if b.type == "equation":
        lab = safe_label(b.label)
        return ("\\begin{equation}\n" + sanitize_math(b.text or "") + (f"\\label{{{lab}}}" if lab else "")
                + "\n\\end{equation}\n")
    if b.type == "figure":
        fname = safe_filename(b.figure_file or "")
        lab = safe_label(b.label)
        width = max(0.2, min(1.0, b.width))
        return ("\\begin{figure}[t]\n\\centering\n"
                f"\\includegraphics[width={width:.2f}\\linewidth]{{figures/{fname}}}\n"
                f"\\caption{{{inline(b.caption or '')}}}" + (f"\\label{{{lab}}}" if lab else "") + "\n\\end{figure}\n")
    if b.type == "table":
        cols = max(len(b.header), max((len(r) for r in b.rows), default=0))
        if cols == 0:
            raise AdapterError("table has no columns")
        lab = safe_label(b.label)
        lines = ["\\begin{table}[t]", "\\centering", f"\\caption{{{inline(b.caption or '')}}}" + (f"\\label{{{lab}}}" if lab else ""),
                 "\\begin{tabular}{" + "l" * cols + "}", "\\toprule"]
        if b.header:
            lines.append(" & ".join(escape(h) for h in b.header) + " \\\\")
            lines.append("\\midrule")
        for r in b.rows:
            cells = [escape(c) for c in r] + [""] * (cols - len(r))
            lines.append(" & ".join(cells) + " \\\\")
        lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
        return "\n".join(lines) + "\n"
    raise AdapterError(f"unsupported block {b.type}")


def _section(s: Section) -> str:
    star = "*" if s.unnumbered else ""
    lab = safe_label(s.label)
    head = f"\\section{star}{{{escape(s.heading)}}}" + (f"\\label{{{lab}}}" if lab else "") + "\n"
    return head + "\n".join(_block(b) for b in s.blocks) + "\n"


def content_tex(doc: ManuscriptDocument) -> str:
    out = "% Generated by " + ADAPTER_VERSION + ". Edit content through the platform, not here.\n"
    out += "".join(_section(s) for s in doc.sections)
    if doc.appendix:
        out += "\\appendix\n" + "".join(_section(s) for s in doc.appendix)
    return out


def _acks(doc: ManuscriptDocument, opts: RenderOptions, env: str | None) -> str:
    if opts.anonymous or not doc.acknowledgments:
        return ""
    if env:
        return f"\\begin{{{env}}}\n{inline(doc.acknowledgments)}\n\\end{{{env}}}\n"
    return "\\section*{Acknowledgments}\n" + inline(doc.acknowledgments) + "\n"


def _bib(opts: RenderOptions, style: str | None, family: str) -> tuple[str, str]:
    if opts.bib_mode == "biber":
        if family != "acmart":
            raise AdapterError(f"the {family} template documents BibTeX only; Biber mode is not supported")
        return "", "\\printbibliography\n"
    if not style:
        raise AdapterError("no bibliography style available in the template")
    return "", f"\\bibliographystyle{{{style}}}\n\\bibliography{{refs}}\n"


def render(family: str, doc: ManuscriptDocument, opts: RenderOptions, bib_style: str | None) -> dict[str, str]:
    authors = doc.authors
    if opts.anonymous or not authors:
        from rp_contracts.latexdoc import Author

        authors = [Author(name=ANON_NAME, affiliation=ANON_AFFIL)]
    kw = ", ".join(escape(k) for k in doc.keywords)
    pre, post = _bib(opts, bib_style, family)
    if family == "acmart":
        options = ["sigconf"]
        if opts.anonymous:
            options += ["review", "anonymous"]
        if opts.bib_mode == "biber":
            options.append("natbib=false")
        head = f"\\documentclass[{','.join(options)}]{{acmart}}\n"
        if opts.bib_mode == "biber":
            head += "\\RequirePackage[datamodel=acmdatamodel,style=acmnumeric]{biblatex}\n\\addbibresource{refs.bib}\n"
        head += "\\usepackage{booktabs}\n"
        if opts.mode == "submission":
            head += "\\setcopyright{none}\n\\settopmatter{printacmref=false}\n\\renewcommand\\footnotetextcopyrightpermission[1]{}\n"
        if opts.anonymous:
            head += "\\hypersetup{pdfauthor={},pdfsubject={},pdfkeywords={}}\n"
        auth = "".join(
            f"\\author{{{escape(a.name)}}}\n\\affiliation{{\\institution{{{escape(a.affiliation or ANON_AFFIL)}}}"
            f"\\country{{{escape(a.country or '')}}}}}\n" + (f"\\email{{{escape(a.email)}}}\n" if a.email else "")
            for a in authors)
        body = (f"\\begin{{document}}\n\\title{{{escape(doc.title)}}}\n{auth}"
                f"\\begin{{abstract}}\n{inline(doc.abstract)}\n\\end{{abstract}}\n"
                + (f"\\keywords{{{kw}}}\n" if kw else "") + "\\maketitle\n\\input{content}\n"
                + _acks(doc, opts, "acks") + post + "\\end{document}\n")
        main = head + pre + body
    elif family == "ieeetran":
        head = ("\\documentclass[conference]{IEEEtran}\n\\usepackage{cite}\n\\usepackage{amsmath,amssymb}\n"
                "\\usepackage{graphicx}\n\\usepackage{booktabs}\n\\usepackage{url}\n")
        if opts.anonymous:
            head += "\\pdfinfo{/Author ()}\n"
        blocks = "\n\\and\n".join(
            f"\\IEEEauthorblockN{{{escape(a.name)}}}\n\\IEEEauthorblockA{{\\textit{{{escape(a.affiliation or ANON_AFFIL)}}}"
            + (f"\\\\ {escape(a.email)}" if a.email else "") + "}" for a in authors)
        main = (head + f"\\begin{{document}}\n\\title{{{escape(doc.title)}}}\n\\author{{{blocks}}}\n\\maketitle\n"
                f"\\begin{{abstract}}\n{inline(doc.abstract)}\n\\end{{abstract}}\n"
                + (f"\\begin{{IEEEkeywords}}\n{kw}\n\\end{{IEEEkeywords}}\n" if kw else "")
                + "\\input{content}\n" + _acks(doc, opts, None) + post + "\\end{document}\n")
    elif family == "llncs":
        head = "\\documentclass[runningheads]{llncs}\n\\usepackage{graphicx}\n\\usepackage{booktabs}\n\\usepackage{amsmath}\n"
        if opts.anonymous:
            head += "\\pdfinfo{/Author ()}\n"
        names = " \\and ".join(f"{escape(a.name)}\\inst{{{i}}}" for i, a in enumerate(authors, start=1))
        insts = " \\and ".join(escape(a.affiliation or ANON_AFFIL) + (f"\\\\ \\email{{{escape(a.email)}}}" if a.email else "")
                               for a in authors)
        main = (head + f"\\begin{{document}}\n\\title{{{escape(doc.title)}}}\n\\author{{{names}}}\n"
                f"\\authorrunning{{{'Anonymous' if opts.anonymous else escape(authors[0].name)}}}\n\\institute{{{insts}}}\n\\maketitle\n"
                f"\\begin{{abstract}}\n{inline(doc.abstract)}\n"
                + (f"\\keywords{{{' \\and '.join(escape(k) for k in doc.keywords)}}}\n" if doc.keywords else "")
                + "\\end{abstract}\n\\input{content}\n" + _acks(doc, opts, None) + post + "\\end{document}\n")
    else:
        raise AdapterError(f"no adapter for template family {family!r}")
    return {"main.tex": main, "content.tex": content_tex(doc), "refs.bib": doc.bibtex or ""}


def sample_document() -> ManuscriptDocument:
    """Fixed sample used for template validation compiles (clearly labelled as sample content)."""
    from rp_contracts.latexdoc import Author

    return ManuscriptDocument(
        title="Template Validation Sample (not a manuscript)",
        abstract="This sample checks that the official template compiles with inserted content, citations "
                 "[@sample2024], a figure and a table. It contains no research findings.",
        keywords=["template validation", "sample"],
        authors=[Author(name="Sample Author", affiliation="Sample University", country="Nowhere",
                        email="sample.author@example.org")],
        sections=[
            Section(heading="Introduction", label="sec:intro", blocks=[
                Block(type="paragraph", text="Placeholder text for layout testing only, citing [@sample2024; @other2023]."),
                Block(type="equation", text=r"\hat{y} = \frac{1}{n}\sum_{i=1}^{n} x_i", label="eq:mean")]),
            Section(heading="Figures and Tables", blocks=[
                Block(type="figure", figure_file="sample-figure.pdf", caption="A sample figure.", label="fig:sample"),
                Block(type="table", caption="A sample table.", label="tab:sample", header=["Item", "Value"],
                      rows=[["alpha", "1"], ["beta", "2"]])]),
        ],
        acknowledgments="Sample acknowledgment that must be absent from anonymous builds.",
        bibtex=("@inproceedings{sample2024, author={A. Sample}, title={A Sample Reference}, booktitle={Proceedings "
                "of Samples}, year={2024}}\n@article{other2023, author={B. Other}, title={Another Reference}, "
                "journal={Journal of Examples}, year={2023}, volume={1}, pages={1--2}}\n"),
    )
